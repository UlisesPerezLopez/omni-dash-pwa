/**
 * Flattens nested dictionary for backwards compatibility with existing flat keys.
 */
function createFlatDictionary(locale: LocaleSchema): Record<string, string> {
  const flat: Record<string, string> = {};

  const traverse = (obj: Record<string, any>, prefix = "") => {
    for (const [key, val] of Object.entries(obj)) {
      const fullPath = prefix ? `${prefix}.${key}` : key;
      if (typeof val === "string") {
        flat[fullPath] = val;
        flat[fullPath.toLowerCase()] = val;
        const normPath = fullPath.toLowerCase().replace(/[\s_\-.]+/g, "");
        if (!flat[normPath]) flat[normPath] = val;

        // Also register leaf key directly if not already registered
        if (!flat[key]) {
          flat[key] = val;
        }
        if (!flat[key.toLowerCase()]) {
          flat[key.toLowerCase()] = val;
        }
        const normKey = key.toLowerCase().replace(/[\s_\-]+/g, "");
        if (!flat[normKey]) {
          flat[normKey] = val;
        }
      } else if (typeof val === "object" && val !== null) {
        traverse(val, fullPath);
      }
    }
  };

  traverse(locale);
  return flat;
}

export const flatLocales: Record<Language, Record<string, string>> = {
  en: createFlatDictionary(locales.en),
  es: createFlatDictionary(locales.es),
  de: createFlatDictionary(locales.de),
  fr: createFlatDictionary(locales.fr),
  it: createFlatDictionary(locales.it),
  zh: createFlatDictionary(locales.zh),
  ja: createFlatDictionary(locales.ja),
};

/**
 * Returns a translation function for the specified language.
 */
export function getTranslator(language: Language) {
  const current = flatLocales[language] || flatLocales.en;
  const fallback = flatLocales.en;

  return (key: string, defaultText?: string): string => {
    if (!key) return defaultText || "";
    // 1. Direct match in active language
    if (current[key]) return current[key];
    // 2. Case-insensitive lookup
    const lowerKey = key.toLowerCase();
    if (current[lowerKey]) return current[lowerKey];
    // 3. Normalized alphanumeric lookup
    const normKey = lowerKey.replace(/[\s_\-.]+/g, "");
    if (current[normKey]) return current[normKey];
    // 4. Fallback to English
    if (fallback[key]) return fallback[key];
    if (fallback[lowerKey]) return fallback[lowerKey];
    if (fallback[normKey]) return fallback[normKey];
    // 5. Default text or key itself
    return defaultText || key;
  };
}
